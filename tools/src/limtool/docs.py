"""Docs frontmatter parsing, index generation, linting and search."""

import re
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

import yaml

INDEX_NAME = "INDEX.md"
SOFT_LIMIT = 150
HARD_LIMIT = 250
REQUIRED_FIELDS = ("title", "summary", "tags", "status", "updated")
STATUSES = {"draft", "proposed", "accepted", "superseded", "deprecated", "current"}
KEBAB = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*(\.[a-z0-9]+)*$")
LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)


@dataclass
class Doc:
    path: Path
    rel: str
    meta: dict
    body: str
    lines: int
    errors: list[str] = field(default_factory=list)


def parse(path: Path, root: Path) -> Doc:
    text = path.read_text(encoding="utf-8")
    rel = path.relative_to(root).as_posix()
    match = FRONTMATTER.match(text)
    meta: dict = {}
    errors: list[str] = []
    if not match:
        errors.append("missing frontmatter")
        body = text
    else:
        try:
            meta = yaml.safe_load(match.group(1)) or {}
        except yaml.YAMLError as exc:
            errors.append(f"invalid frontmatter: {exc}")
        body = text[match.end() :]
    return Doc(path, rel, meta, body, text.count("\n") + 1, errors)


def collect(root: Path) -> list[Doc]:
    return [parse(p, root) for p in sorted(root.rglob("*.md")) if p.name != INDEX_NAME]


def lint(root: Path) -> tuple[list[str], list[str]]:
    """Return (errors, warnings) as 'path: message' strings."""
    errors: list[str] = []
    warnings: list[str] = []
    for doc in collect(root):
        errs = list(doc.errors)
        meta = doc.meta
        if not doc.errors:
            errs += [f"missing field '{f}'" for f in REQUIRED_FIELDS if f not in meta]
            status = meta.get("status")
            if status is not None and status not in STATUSES:
                errs.append(f"invalid status '{status}' (allowed: {sorted(STATUSES)})")
            if "tags" in meta and not isinstance(meta["tags"], list):
                errs.append("tags must be a list")
            if not isinstance(meta.get("updated", date.today()), (date, str)):
                errs.append("updated must be YYYY-MM-DD")
            if doc.rel.startswith("knowledge/") and not meta.get("sources"):
                errs.append("knowledge docs require 'sources'")
        stem = doc.path.name.removesuffix(".md")
        if doc.path.name != "README.md" and not KEBAB.match(stem):
            errs.append("file name must be kebab-case")
        if doc.lines > HARD_LIMIT:
            errs.append(f"{doc.lines} lines exceeds hard limit {HARD_LIMIT} — split it")
        elif doc.lines > SOFT_LIMIT:
            warnings.append(f"{doc.rel}: {doc.lines} lines exceeds soft limit {SOFT_LIMIT}")
        for target in LINK.findall(doc.body):
            if re.match(r"^[a-z]+:", target) or target.startswith("#"):
                continue
            resolved = (doc.path.parent / target.split("#", 1)[0]).resolve()
            if not resolved.exists():
                errs.append(f"broken link '{target}'")
        errors += [f"{doc.rel}: {e}" for e in errs]
    return errors, warnings


def render_index(root: Path) -> str:
    docs = collect(root)
    groups: dict[str, list[Doc]] = {}
    for doc in docs:
        group = doc.rel.rsplit("/", 1)[0] if "/" in doc.rel else "."
        groups.setdefault(group, []).append(doc)
    out = [
        "# Documentation index",
        "",
        "<!-- GENERATED by `limtool docs index` — do not edit by hand. -->",
        "",
        f"{len(docs)} documents. Search: `uv run --project tools limtool docs search <terms>`.",
        "",
    ]
    for group in sorted(groups):
        out += [f"## {group}", "", "| Document | Summary | Status | Tags |", "|---|---|---|---|"]
        for doc in groups[group]:
            title = doc.meta.get("title", doc.path.stem)
            summary = str(doc.meta.get("summary", "")).replace("|", "\\|")
            tags = ", ".join(doc.meta.get("tags", []) or [])
            out.append(f"| [{title}]({doc.rel}) | {summary} | {doc.meta.get('status', '')} | {tags} |")
        out.append("")
    return "\n".join(out)


def search(root: Path, terms: list[str], tag: str | None = None) -> list[tuple[int, Doc]]:
    """Rank docs by term hits: title x5, summary/tags x3, body x1. All terms must match."""
    needles = [t.lower() for t in terms]
    hits: list[tuple[int, Doc]] = []
    for doc in collect(root):
        tags = [str(t).lower() for t in doc.meta.get("tags", []) or []]
        if tag and tag.lower() not in tags:
            continue
        title = str(doc.meta.get("title", "")).lower()
        head = str(doc.meta.get("summary", "")).lower() + " " + " ".join(tags)
        body = doc.body.lower()
        score = 0
        for n in needles:
            s = 5 * title.count(n) + 3 * head.count(n) + body.count(n)
            if s == 0:
                break
            score += s
        else:
            hits.append((score, doc))
    return sorted(hits, key=lambda h: -h[0])
